#!/usr/bin/env python3
"""
gen_cli_parity_cases.py -- make rust/doc/CLI-PARITY-CASES.md: the wrong command lines of
PARITY_CLI_ERROR_CASES (tools/softflowd_test_parity_live.py) run with C and with Rust.

  tools/gen_cli_parity_cases.py [--a ./softflowd] [--b rust/target/release/rsoftflowd]
                                [--pcap pcaps/http.cap] [--out rust/doc/CLI-PARITY-CASES.md]

For each case: the exit status, the stream and the first line of C and of Rust, and whether the
whole of standard output, standard error and the exit status are the same (the same text that the
parity check compares: the program name, the version and the paths are hidden).
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

import softflowd_test_parity_live as live


def clean(text: str, daemon: str, tmp: str, pcap: str) -> str:
    text = text.replace(tmp, "TMP").replace(pcap, "PCAP")
    text = live._hide_program_name(text.replace("/var/run/softflowd.", "/var/run/DEFAULT."), daemon)
    text = re.sub(r"version \d+\.\d+\.\d+", "version X", text)
    text = re.sub(r"PROG v\d+\.\d+\.\d+ ", "PROG vX ", text)
    return re.sub(r"This project's own additions[^\n]*\n(?:  [^\n]*\n)*", "", text)


def run(daemon: str, args, tmp: str, pcap: str):
    try:
        r = subprocess.run([daemon] + args, capture_output=True, text=True, timeout=10,
                           stdin=subprocess.DEVNULL, cwd=tmp)
    except subprocess.TimeoutExpired:
        return "", "", "TIMEOUT"
    return clean(r.stdout, daemon, tmp, pcap), clean(r.stderr, daemon, tmp, pcap), r.returncode


def first_line(out: str, err: str):
    for stream, text in (("stderr", err), ("stdout", out)):
        if text.strip():
            return stream, text.strip().splitlines()[0]
    return "-", ""


def main() -> int:
    ap = argparse.ArgumentParser(description="make rust/doc/CLI-PARITY-CASES.md")
    ap.add_argument("--a", default="./softflowd")
    ap.add_argument("--b", default="rust/target/release/rsoftflowd")
    ap.add_argument("--pcap", default="pcaps/http.cap")
    ap.add_argument("--out", default=os.path.join("rust", "doc", "CLI-PARITY-CASES.md"))
    args = ap.parse_args()
    a_bin, b_bin, pcap = (os.path.abspath(args.a), os.path.abspath(args.b), os.path.abspath(args.pcap))

    rows, same = [], 0
    with tempfile.TemporaryDirectory(prefix="cli_parity_") as tmp:
        for template in live.PARITY_CLI_ERROR_CASES:
            argv = [a.format(pcap=pcap, ctl=os.path.join(tmp, "c.ctl")) for a in template]
            i = argv.index("-i") if "-i" in argv else -1
            if 0 <= i < len(argv) - 1 and argv[i + 1] == "lo" and not live.parity_can_capture_lo():
                continue                       # needs root, as the parity check
            a, b = run(a_bin, argv, tmp, pcap), run(b_bin, argv, tmp, pcap)
            same += a == b
            (sa, la), (sb, lb) = first_line(a[0], a[1]), first_line(b[0], b[1])
            esc = lambda t: t.replace("|", "\\|")[:100]
            rows.append(f"| `{esc(' '.join(template) or '(no arguments)')}` | {a[2]} | {sa} | {esc(la)} | "
                        f"{b[2]} | {sb} | {esc(lb)} | {'yes' if a == b else 'NO'} |")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# CLI parity cases / コマンドライン比較ケース\n\n")
        f.write("Generated by `tools/gen_cli_parity_cases.py` from `PARITY_CLI_ERROR_CASES` of "
                "`tools/softflowd_test_parity_live.py` with `softflowd` (C) and `rsoftflowd` (Rust). "
                "`PROG` is the program name; `{pcap}` is a capture file. \"same\" compares the whole of "
                "standard output, standard error and the exit status, not the first line only. "
                "A row that is not the same is a known difference with a row in "
                "`rust/doc/DIFFERENCES-FROM-C.en.md`; the gate "
                "(`tools/gate_expected.json`) fails for any other difference. "
                "Run it again after a change to the command line of either binary: "
                "`cd tools && python3 gen_cli_parity_cases.py --a ../softflowd "
                "--b ../rust/target/release/rsoftflowd --pcap ../pcaps/http.cap`.\n\n")
        f.write(f"{same} of {len(rows)} cases are the same.\n\n")
        f.write("| args | C exit | C stream | C first line | Rust exit | Rust stream | Rust first line | same |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print(f"wrote {args.out}: {same} of {len(rows)} cases are the same")
    return 0


if __name__ == "__main__":
    sys.exit(main())
